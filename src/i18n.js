let lang = 'de';
try { if (localStorage.getItem(LANG_KEY) in STRINGS) lang = localStorage.getItem(LANG_KEY); } catch (e) { /* storage unavailable */ }
document.documentElement.lang = lang;

function t(key, ...args) {
  const entry = STRINGS[lang][key] ?? STRINGS.de[key];
  return typeof entry === 'function' ? entry(...args) : entry;
}

function setLanguage(code) {
  if (!(code in STRINGS)) return;
  lang = code;
  document.documentElement.lang = code;
  try { localStorage.setItem(LANG_KEY, code); } catch (e) { /* storage unavailable */ }
}
